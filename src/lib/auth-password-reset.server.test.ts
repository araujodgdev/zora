import { afterAll, beforeEach, describe, expect, it } from 'vitest'
import { closeTestDb, createTestDb, resetDatabase } from '../../test/db'
import { createAuth } from './auth.server'
import type { Mailer, OutgoingEmail } from './mailer.server'

const db = await createTestDb()
const sent: Array<OutgoingEmail> = []
const mailer: Mailer = {
  async send(message) {
    sent.push(message)
    return { messageId: 'reset-1' }
  },
}

const auth = createAuth(
  db,
  {
    BETTER_AUTH_SECRET: 'test-secret-test-secret-test-secret-123',
    BETTER_AUTH_URL: 'http://localhost:3000',
  },
  { mailer },
)

beforeEach(async () => {
  await resetDatabase(db)
  sent.length = 0
})

afterAll(async () => {
  await closeTestDb(db)
})

describe('password reset flow', () => {
  it('sends a pt-BR reset email and lets the user sign in with the new password', async () => {
    const email = 'criadora@example.com'
    const oldPassword = 'old-password-1234'
    const newPassword = 'new-password-5678'

    const signedUp = await auth.api.signUpEmail({
      body: { name: 'Clara', email, password: oldPassword },
      asResponse: true,
    })
    expect(signedUp.status).toBe(200)

    const requested = await auth.api.requestPasswordReset({
      body: {
        email,
        redirectTo: 'http://localhost:3000/reset-password',
      },
    })
    expect(requested.status).toBe(true)
    expect(sent).toHaveLength(1)
    expect(sent[0]!.to).toBe(email)
    expect(sent[0]!.subject).toContain('Redefinir')
    expect(sent[0]!.html).toContain('Clara')

    // Extract the reset token from the link generated by Better Auth.
    const urlMatch = sent[0]!.text.match(/https?:\/\/\S+/)
    expect(urlMatch).not.toBeNull()
    const resetUrl = new URL(urlMatch![0])
    const token =
      resetUrl.searchParams.get('token') ??
      resetUrl.pathname.split('/').filter(Boolean).pop() ??
      ''
    expect(token.length).toBeGreaterThan(10)

    const resetResult = await auth.api.resetPassword({
      body: { newPassword, token },
    })
    expect(resetResult.status).toBe(true)

    // Old password must fail; new password must succeed.
    const oldLogin = await auth.api.signInEmail({
      body: { email, password: oldPassword },
      asResponse: true,
    })
    expect(oldLogin.status).toBe(401)

    const newLogin = await auth.api.signInEmail({
      body: { email, password: newPassword },
      asResponse: true,
    })
    expect(newLogin.status).toBe(200)
  })

  it('rejects an invalid reset token', async () => {
    const res = await auth.api.resetPassword({
      body: { newPassword: 'new-password-5678', token: 'invalid-token-value' },
      asResponse: true,
    })
    expect(res.ok).toBe(false)
  })
})
